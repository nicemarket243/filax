let lang: Lang = "fr";
const listeners = new Set<() => void>();
if (typeof window !== "undefined" && localStorage.getItem(LANG_KEY) === "en") lang = "en";

export function setLang(next: Lang) {
  lang = next;
  localStorage.setItem(LANG_KEY, next);
  document.documentElement.lang = next;
  listeners.forEach((l) => l());
}

const subscribe = (l: () => void) => {
  listeners.add(l);
  return () => listeners.delete(l);
};

export function translate(text: string, l: Lang) {
  if (l !== "en") return text;
  if (EN[text]) return EN[text];
  let result = text;
  for (const [source, target] of Object.entries(EN).sort((a, b) => b[0].length - a[0].length)) {
    if (result.includes(source)) result = result.split(source).join(target);
  }
  return result
    .replace(/(\d+) groupe(s?)/g, "$1 group$2")
    .replace(/(\d+) membre(s?)/g, "$1 member$2")
    .replace(/(\d+) opération\(s\)/g, "$1 transaction(s)")
    .replace(/ sur /g, " of ");
}

export function useI18n() {
  const current = useSyncExternalStore(subscribe, () => lang, () => "fr" as Lang);
  return { lang: current, setLang, t: (text: string) => translate(text, current) };
}

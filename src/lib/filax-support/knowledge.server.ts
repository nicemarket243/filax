export const SUPPORT_FAQ = SUPPORT_TOPICS.flatMap((topic, index) =>
  QUESTION_FORMS.map((form, variant) => ({
    id: `${index + 1}-${variant + 1}`,
    question: form.replace("{q}", topic.question),
    answer: topic.answer,
  })),
);
export function supportContext(question: string) {
  const words =
    question
      .toLowerCase()
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .match(/[a-z]{4,}/g) ?? [];
  return SUPPORT_TOPICS.map((topic) => ({
    topic,
    score: words.reduce(
      (score, word) =>
        score +
        Number(
          (topic.question + " " + topic.answer)
            .toLowerCase()
            .normalize("NFD")
            .replace(/[\u0300-\u036f]/g, "")
            .includes(word),
        ),
      0,
    ),
  }))
    .sort((a, b) => b.score - a.score)
    .slice(0, 10)
    .map(({ topic }) => `${topic.question}\n${topic.answer}`)
    .join("\n\n");
}
